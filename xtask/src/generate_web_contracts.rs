//! `xtask generate-web-contracts` — emit web account contract types and
//! runtime validators from Rust JSON Schema sources.

use anyhow::{Context, Result};
use schemars::schema_for;
use serde_json::{Map, Value, json};
use std::collections::{BTreeSet, HashSet};
use std::fmt::Write as _;
use std::fs;
use std::io::Write;
use std::path::Path;
use tanren_contract::{
    AccountFailureReason, AccountView, ActiveAccountView, ListActiveAccountsRequest,
    ListActiveAccountsResponse, SessionEnvelope, SignedInAccountView, SwitchActiveAccountRequest,
    SwitchActiveAccountResponse,
};
use tanren_identity_policy::{AccountId, Identifier, OrgId};

const OUTPUT_PATH: &str = "apps/web/src/app/lib/generated/account-contract.ts";

pub(crate) fn run(root: &Path) -> Result<()> {
    let output = root.join(OUTPUT_PATH);
    let parent = output
        .parent()
        .context("generated web contract path has no parent")?;
    fs::create_dir_all(parent)
        .with_context(|| format!("create generated dir {}", parent.display()))?;

    let contents = render_contract_file();
    fs::write(&output, contents).with_context(|| format!("write {}", output.display()))?;

    let stdout = std::io::stdout();
    let mut handle = stdout.lock();
    let _ = writeln!(handle, "generate-web-contracts: wrote {}", output.display());
    Ok(())
}

#[derive(Debug)]
struct SchemaTarget {
    name: &'static str,
    schema: Value,
    brand: Option<&'static str>,
}

fn render_contract_file() -> String {
    let targets = schema_targets();
    let mut rendered = String::new();
    render_header(&mut rendered);
    render_schema_exports(&mut rendered, &targets);
    render_parse_helpers(&mut rendered, &targets);
    render_failure_code_union(&mut rendered);
    rendered
}

